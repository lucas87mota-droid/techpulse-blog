-- Tabela usada pelo formulário de newsletter do TechPulse.
create table if not exists public.inscritos (
  id bigint generated by default as identity primary key,
  email text not null unique,
  data_cadastro timestamp with time zone default now()
);

-- Mantém a tabela protegida para acesso direto pelo cliente.
alter table public.inscritos enable row level security;

